#!/usr/bin/env node
/* Regenerates the /go/<slug> redirect block in public/_redirects from public/data/offers.json.
   Single source of truth: edit "target" (the real tracking URL) there, then run this script. */
const fs = require('fs'); const path = require('path');
const PUB = path.join(__dirname, '..', 'public');
const offers = JSON.parse(fs.readFileSync(path.join(PUB, 'data', 'offers.json'), 'utf8')).offers.filter((o) => o.slug);
const START = '# >>> affiliate redirects (generated by scripts/build-affiliate-redirects.js) >>>';
const END = '# <<< affiliate redirects <<<';
const lines = [START, '# Placeholder targets fall back to /loans/ until a real tracking URL is set in data/offers.json.'];
for (const o of offers) {
  const ok = /^https:\/\//.test(o.target || '');
  lines.push(`/go/${o.slug} ${ok ? o.target : '/loans/'} 302`);
}
lines.push(END);
const fp = path.join(PUB, '_redirects');
let cur = fs.readFileSync(fp, 'utf8');
const re = new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?');
cur = re.test(cur) ? cur.replace(re, lines.join('\n') + '\n') : cur.replace(/\n*$/, '\n\n') + lines.join('\n') + '\n';
fs.writeFileSync(fp, cur);
console.log(`wrote ${offers.length} /go/ redirects`);
