#!/usr/bin/env node
/* Generates public/js/sba-policy.js (window.LF_POLICY) from public/data/sba-policy.json so the browser calculators use the same values.
   Run after editing sba-policy.json; the daily workflow runs it too. */
const fs = require('fs'), path = require('path');
const PUB = path.join(__dirname, '..', 'public');
const p = JSON.parse(fs.readFileSync(path.join(PUB, 'data', 'sba-policy.json'), 'utf8')); delete p._help;
fs.writeFileSync(path.join(PUB, 'js', 'sba-policy.js'), '/* Generated by scripts/sync-policy.js from data/sba-policy.json. Do not edit. */\nwindow.LF_POLICY = ' + JSON.stringify(p) + ';\n');
let n = 0;
for (const dir of ['calculators', 'loans']) for (const f of fs.readdirSync(path.join(PUB, dir)).filter((x) => x.endsWith('.html'))) {
  const fp = path.join(PUB, dir, f); let h = fs.readFileSync(fp, 'utf8');
  if (!/<script src="\/js\/lf-math\.js[^"]*"><\/script>/.test(h) || h.includes('/js/sba-policy.js')) continue;
  h = h.replace(/(<script src="\/js\/lf-math\.js[^"]*"><\/script>)/, '<script src="/js/sba-policy.js"></script>\n$1'); fs.writeFileSync(fp, h); n++;
}
console.log('policy script written; added to', n, 'pages');
